    private void searchh() {
        DefaultTableModel model = (DefaultTableModel) tbl.getModel();
        String keyword = searchbar.getText().trim();

        // Attach a TableRowSorter to your table
        javax.swing.table.TableRowSorter<DefaultTableModel> sorter = new javax.swing.table.TableRowSorter<>(model);
        tbl.setRowSorter(sorter);

        if (keyword.isEmpty()) {
            // If search bar is empty, show all rows again
            sorter.setRowFilter(null);
        } else {
            // Filter rows that contain the keyword (case-insensitive)
            sorter.setRowFilter(javax.swing.RowFilter.regexFilter("(?i)" + keyword));
        }
    }

