    private void addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addActionPerformed
        DefaultTableModel model = (DefaultTableModel) tbl.getModel();

        if (name.getText().trim().isEmpty() || Expiration.getText().isEmpty() || c.getSelectedItem().toString() == "---" || price.getText().isEmpty() || quantity.getText().isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "Check your entry!");
        } else {
            String row[] = {name.getText(), Expiration.getText(), c.getSelectedItem().toString(), price.getText(), quantity.getText()};
            model.addRow(row);

            JOptionPane.showMessageDialog(rootPane, "Added Successfully!");
            clearentry();
        }
    }//GEN-LAST:event_addActionPerformed

    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
        DefaultTableModel model = (DefaultTableModel) tbl.getModel();

        if (name.getText().trim().isEmpty() || Expiration.getText().isEmpty() || c.getSelectedItem().toString() == "---" || price.getText().isEmpty() || quantity.getText().isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "Click an Existing data before updating!");
        }

        int selrow = tbl.getSelectedRow();

        if (selrow >= 0) {

            model.setValueAt(name.getText(), selrow, 0);
            model.setValueAt(Expiration.getText(), selrow, 1);
            model.setValueAt(c.getSelectedItem(), selrow, 2);
            model.setValueAt(price.getText(), selrow, 3);
            model.setValueAt(quantity.getText(), selrow, 4);

            JOptionPane.showMessageDialog(rootPane, "Updated Successfully!");
        }

        clearentry();
    }//GEN-LAST:event_updateActionPerformed

    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        DefaultTableModel model = (DefaultTableModel) tbl.getModel();

        if (name.getText().trim().isEmpty() || Expiration.getText().isEmpty() || c.getSelectedItem().toString() == "---" || price.getText().isEmpty() || quantity.getText().isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "Click an Existing data before deleting!");
        }

        int selrow = tbl.getSelectedRow();
        model.removeRow(selrow);

        JOptionPane.showMessageDialog(rootPane, "Deleted Successfully!");

        clearentry();
    }//GEN-LAST:event_deleteActionPerformed

    private void tblMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMouseClicked
        DefaultTableModel model = (DefaultTableModel) tbl.getModel();

        // selected row = selrow
        int selrow = tbl.getSelectedRow();

        name.setText(model.getValueAt(selrow, 0).toString());
        Expiration.setText(model.getValueAt(selrow, 1).toString());
        c.setSelectedItem(model.getValueAt(selrow, 2).toString());
        price.setText(model.getValueAt(selrow, 3).toString());
        quantity.setText(model.getValueAt(selrow, 4).toString());
    }//GEN-LAST:event_tblMouseClicked

